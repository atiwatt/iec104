import { createHash } from 'node:crypto';
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, extname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const publicDirectory = join(root, 'public');
const mimeTypes = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.svg': 'image/svg+xml; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8',
  '.xml': 'application/xml; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
};
const assets = Object.create(null);
const maximumAssetBytes = 256 * 1024;
const maximumTotalBytes = 1024 * 1024;
const maximumFiles = 48;
let totalBytes = 0;

async function collect(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.name.startsWith('.')) throw new Error(`Hidden files are not publishable: ${entry.name}`);
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      await collect(path);
      continue;
    }
    if (!entry.isFile()) throw new Error(`Only regular assets are publishable: ${entry.name}`);
    const contentType = mimeTypes[extname(entry.name)];
    if (!contentType) throw new Error(`Unsupported asset extension: ${entry.name}`);
    const bytes = await readFile(path);
    if (bytes.byteLength > maximumAssetBytes) throw new Error(`Asset exceeds 256 KiB: ${entry.name}`);
    const body = new TextDecoder('utf-8', { fatal: true }).decode(bytes);
    totalBytes += bytes.byteLength;
    const assetPath = '/' + relative(publicDirectory, path).split(sep).join('/');
    assets[assetPath] = {
      body,
      contentType,
      etag: '"' + createHash('sha256').update(bytes).digest('hex').slice(0, 32) + '"',
      bytes: bytes.byteLength,
    };
    if (Object.keys(assets).length > maximumFiles || totalBytes > maximumTotalBytes) {
      throw new Error('Site exceeds the build limits of 48 files / 1 MiB.');
    }
  }
}

await collect(publicDirectory);
if (!assets['/index.html']) throw new Error('public/index.html is required.');

// The Worker is self-contained: only explicitly collected public assets are deployed.
const worker = `// Generated by scripts/build.mjs. Edit public/ and rebuild.\nconst assets = ${JSON.stringify(assets)};\n` + String.raw`
const securityHeaders = {
  'Content-Security-Policy': "default-src 'none'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; font-src 'self'; connect-src 'none'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'",
  'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=(), usb=()',
  'X-Frame-Options': 'DENY',
  'Content-Language': 'zh-CN, en',
};
const notFound = '<!doctype html><html lang="zh-CN"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>页面未找到 / Page not found · IEC 104</title><style>body{max-width:42rem;margin:15vh auto;padding:2rem;background:#f5f7f0;color:#17372d;font:18px/1.8 system-ui}a{color:#167556}</style><h1>页面未找到</h1><p lang="en">The requested page could not be found.</p><a href="/?lang=zh">返回首页 →</a><p lang="en"><a href="/?lang=en">Return to the English guide →</a></p></html>';

function matchesETag(header, etag) {
  return header?.split(',').some((value) => {
    const normalized = value.trim().replace(/^W\//, '');
    return normalized === '*' || normalized === etag;
  });
}

export default {
  fetch(request) {
    const isHead = request.method === 'HEAD';
    if (request.method !== 'GET' && !isHead) {
      return new Response('Method not allowed', {
        status: 405,
        headers: { ...securityHeaders, Allow: 'GET, HEAD', 'Content-Type': 'text/plain; charset=utf-8', 'Cache-Control': 'no-store' },
      });
    }
    const pathname = new URL(request.url).pathname;
    const key = pathname === '/' ? '/index.html' : pathname;
    if (!Object.hasOwn(assets, key)) {
      return new Response(isHead ? null : notFound, {
        status: 404,
        headers: { ...securityHeaders, 'Content-Type': 'text/html; charset=utf-8', 'Cache-Control': 'no-store' },
      });
    }
    const asset = assets[key];
    const headers = {
      ...securityHeaders,
      'Content-Type': asset.contentType,
      'Cache-Control': key.endsWith('.html') ? 'public, max-age=0, must-revalidate' : 'public, max-age=300, must-revalidate',
      ETag: asset.etag,
    };
    if (matchesETag(request.headers.get('If-None-Match'), asset.etag)) {
      return new Response(null, { status: 304, headers });
    }
    return new Response(isHead ? null : asset.body, { status: 200, headers });
  },
};
`;
await mkdir(join(root, 'dist'), { recursive: true });
await writeFile(join(root, 'dist', 'worker.mjs'), worker, 'utf8');
console.log(`Built ${Object.keys(assets).length} public assets (${totalBytes.toLocaleString('en-US')} bytes) into dist/worker.mjs.`);
